import os
from pathlib import Path
from backend.app.core.config import settings
from backend.app.core.security import ALLOWED_TERRAFORM_RESOURCES, sanitize_string
from backend.app.database.models import ResourceModel, OptimizationProposalModel

TERRAFORM_GENERATED_DIR = Path(__file__).resolve().parents[3] / "terraform" / "generated"

class TerraformAgent:
    def __init__(self):
        TERRAFORM_GENERATED_DIR.mkdir(parents=True, exist_ok=True)

    def generate_terraform(self, resource: ResourceModel, proposal: OptimizationProposalModel) -> str:
        """Generate safe, deterministic, formatted Infrastructure-as-Code for the proposal."""
        action = proposal.recommended_action
        res_id = sanitize_string(resource.resource_id)
        region = sanitize_string(resource.region)
        name = sanitize_string(resource.resource_name)

        if action == "DOWNSIZE_INSTANCE":
            target_instance = sanitize_string(proposal.recommended_configuration)
            tf_content = f"""# Terraform Configuration Generated by Cloud FinOps Agent
# Optimization Proposal: {proposal.proposal_id}
# Action: Downsize EC2 Instance from {resource.instance_type} to {target_instance}

terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = "{region}"
}}

resource "aws_instance" "{name.replace('-', '_')}" {{
  ami           = "ami-0c55b159cbfafe1f0"
  instance_type = "{target_instance}"

  tags = {{
    Name            = "{name}"
    ManagedBy       = "CloudFinOpsAgent"
    ProposalId      = "{proposal.proposal_id}"
    OriginalId      = "{res_id}"
    OriginalType    = "{resource.instance_type}"
    Environment     = "{resource.environment}"
  }}

  lifecycle {{
    create_before_destroy = false
    prevent_destroy       = true
  }}
}}
"""
        elif action == "DELETE_UNATTACHED_VOLUME":
            tf_content = f"""# Terraform Configuration Generated by Cloud FinOps Agent
# Optimization Proposal: {proposal.proposal_id}
# Action: Snapshot & Deprecate Unattached Volume

terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = "{region}"
}}

# Step 1: Retain Safety Snapshot before volume termination
resource "aws_ebs_snapshot" "{name.replace('-', '_')}_pre_delete_backup" {{
  volume_id   = "{res_id}"
  description = "Safety snapshot generated by FinOps Agent before unattached volume cleanup ({res_id})"

  tags = {{
    Name        = "{name}-safety-backup"
    ManagedBy   = "CloudFinOpsAgent"
    ProposalId  = "{proposal.proposal_id}"
    TargetVolume= "{res_id}"
  }}
}}
"""
        elif action == "DOWNSIZE_DATABASE":
            target_db_class = sanitize_string(proposal.recommended_configuration)
            tf_content = f"""# Terraform Configuration Generated by Cloud FinOps Agent
# Optimization Proposal: {proposal.proposal_id}
# Action: Downsize RDS DB Instance to {target_db_class}

terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = "{region}"
}}

resource "aws_db_instance" "{name.replace('-', '_')}" {{
  identifier            = "{res_id}"
  instance_class        = "{target_db_class}"
  allocated_storage     = 100
  engine                = "postgres"
  apply_immediately     = false
  skip_final_snapshot   = false
  final_snapshot_identifier = "{res_id}-final-snapshot"

  tags = {{
    Name        = "{name}"
    ManagedBy   = "CloudFinOpsAgent"
    ProposalId  = "{proposal.proposal_id}"
    Environment = "{resource.environment}"
  }}
}}
"""
        elif action == "APPLY_S3_LIFECYCLE_TIER":
            tf_content = f"""# Terraform Configuration Generated by Cloud FinOps Agent
# Optimization Proposal: {proposal.proposal_id}
# Action: Configure S3 Lifecycle Archive Tiering

terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = "{region}"
}}

resource "aws_s3_bucket_lifecycle_configuration" "{name.replace('-', '_')}_lifecycle" {{
  bucket = "{res_id}"

  rule {{
    id     = "archive-infrequent-data"
    status = "Enabled"

    transition {{
      days          = 30
      storage_class = "GLACIER_IR"
    }}

    noncurrent_version_expiration {{
      noncurrent_days = 90
    }}
  }}
}}
"""
        else:
            tf_content = f"""# No-op Terraform configuration
# Resource {res_id} requires no modifications
"""

        # Save generated file to disk
        file_path = TERRAFORM_GENERATED_DIR / f"{proposal.proposal_id}.tf"
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(tf_content)

        return tf_content
